// Copies the fonts the page uses (latin, woff2) from @fontsource into build/fonts
// and writes build/fonts.css, so the app needs no network for its typefaces.
import { mkdirSync, copyFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const here = dirname(fileURLToPath(import.meta.url)), root = join(here, '..');
const out = join(root, 'build', 'fonts'); mkdirSync(out, { recursive: true });
const FACES = [['Barlow', 'barlow', [400, 500, 600, 700]], ['Barlow Condensed', 'barlow-condensed', [500, 600, 700]], ['Permanent Marker', 'permanent-marker', [400]]];
let css = '/* generated by scripts/make-fonts.mjs from @fontsource (SIL Open Font License) */\n';
for (const [family, pkg, weights] of FACES) {
  for (const w of weights) {
    const file = `${pkg}-latin-${w}-normal.woff2`, src = join(root, 'node_modules', '@fontsource', pkg, 'files', file);
    if (!existsSync(src)) throw new Error('missing ' + src + ' (run npm install in app/)');
    copyFileSync(src, join(out, file));
    css += `@font-face{font-family:"${family}";font-style:normal;font-weight:${w};font-display:swap;src:url(fonts/${file}) format("woff2")}\n`;
  }
}
writeFileSync(join(root, 'build', 'fonts.css'), css);
console.log('fonts: wrote build/fonts.css and', FACES.reduce((n, f) => n + f[2].length, 0), 'files');
